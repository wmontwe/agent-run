//! The GitHub relay: nginx that ends the agent's connection
//! and opens its own to `api.github.com`, for GET and HEAD to the policy's repositories only,
//! without the agent's headers. One container serves every pod, reached as
//! `http://github-relay:8080`; its repository list changes live.

use podman::{Namespace, OnChange, Podman, PodmanError, Service};
use std::path::Path;

/// The name pods reach the relay by.
pub const ALIAS: &str = "github-relay";
pub const URL: &str = "http://github-relay:8080";

/// nginx's map from request URI to allowed, for `owner/repo` names the policy validated.
/// Case-insensitive, like GitHub's names; a repository's own paths and query only.
pub fn map(repos: &[String]) -> String {
    let mut map =
        String::from("# Generated by agent-run from the policy; changes are overwritten.\n");
    for repo in repos {
        map += &format!("~*^/repos/{}(/|\\?|$) 1;\n", repo.replace('.', "\\."));
    }
    map
}

/// The relay as a shared service: it leaves through the egress proxy's network, which has a
/// route out.
pub fn service<'a>(podman: &'a Podman, namespace: &Namespace, state_dir: &Path) -> Service<'a> {
    Service {
        podman,
        container: namespace.name("github-relay"),
        network: namespace.name("egress"),
        internal: false,
        alias: ALIAS,
        config_dir: state_dir.join("relay"),
        label: namespace.label(),
    }
}

pub struct Relay<'a> {
    pub service: Service<'a>,
    pub image: &'a str,
}

impl Relay<'_> {
    /// Writes the repository list and makes sure the relay runs with it; a running relay
    /// reloads it.
    pub fn ensure(&self, repos: &[String]) -> Result<(), PodmanError> {
        let changed = self
            .service
            .write_config(&[("github-repos.conf", map(repos))])?;
        let options: Vec<String> = [
            "--tmpfs",
            "/tmp:size=64m,mode=1777",
            "--memory",
            "128m",
            "--pids-limit",
            "64",
            "--cpus",
            "1",
            "-v",
            &format!(
                "{}:/etc/nginx/agent-run:ro,z",
                self.service.config_dir.display()
            ),
        ]
        .map(String::from)
        .into();
        self.service
            .ensure(&options, self.image, &[], changed, OnChange::Signal("HUP"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_each_repository_and_nothing_else() {
        let map = map(&["owner/repo".into(), "owner/repo.name".into()]);
        assert!(map.contains("~*^/repos/owner/repo(/|\\?|$) 1;\n"), "{map}");
        assert!(
            map.contains("~*^/repos/owner/repo\\.name(/|\\?|$) 1;\n"),
            "{map}"
        );
        assert_eq!(map.lines().filter(|l| !l.starts_with('#')).count(), 2);
        assert!(!super::map(&[]).lines().any(|l| !l.starts_with('#')));
    }
}
