    #[test]
    fn htpasswd_lines_are_sha512_crypt_as_openssl_writes_it() {
        let line = htpasswd_line("pi-1", "password").unwrap();
        assert!(line.starts_with("pi-1:$6$"), "{line}");
        // A salt crypt() reads whole: `$6$rounds=5000$<16 characters>$<hash>`.
        let salt = line.split('$').nth(3).unwrap();
        assert_eq!(salt.len(), 16, "{line}");
        assert!(htpasswd_matches(&line, "pi-1", "password"));
        assert!(!htpasswd_matches(&line, "pi-1", "other"));
        assert!(!htpasswd_matches(&line, "pi-2", "password"));
        // Salted at random: two lines for one password differ.
        assert_ne!(line, htpasswd_line("pi-1", "password").unwrap());
        // `openssl passwd -6 -salt abcdefgh password`: the format crypt() reads.
        let openssl = "pi-1:$6$abcdefgh$yVfUwsw5T.JApa8POvClA1pQ5peiq97DUNyXCZN5IrF.BMSkiaLQ5kvpuEm/VQ1Tvh/KV2TcaWh8qinoW5dhA1";
        assert!(htpasswd_matches(openssl, "pi-1", "password"));
    }

