    #[test]
    fn each_session_gets_its_own_destinations_and_builds_the_shared_ones() {
        let pi = SessionEgress {
            user: "pi-1a2b".into(),
            allow: vec![destination("chatgpt.com", 443)],
            local: vec![
                destination("192.168.1.50", 1234),
                destination("host.containers.internal", 11434),
            ],
        };
        let claude = SessionEgress {
            user: "claude-3c4d".into(),
            allow: vec![destination("api.anthropic.com", 443)],
            local: vec![],
        };
        let pods = [PodEgress {
            subnet: "10.89.1.0/24".into(),
            allow: vec![destination("registry.npmjs.org", 443)],
            sessions: vec![pi, claude],
        }];
        let c = config(&pods, None);
        let position = |line: &str| {
            c.find(line)
                .unwrap_or_else(|| panic!("missing {line:?} in\n{c}"))
        };
        assert!(c.contains("acl pod0_s0 proxy_auth pi-1a2b\nacl pod0_s1 proxy_auth claude-3c4d\n"));
        // Shared: anyone in the pod, builds included, no credentials needed.
        assert!(c.contains("http_access allow pod0 pod0_d0 pod0_p0\n"));
        // Own: only with the session's credentials.
        assert!(c.contains("acl pod0_s0_d0 dstdomain -n chatgpt.com\n"));
        assert!(c.contains("http_access allow pod0 authed pod0_s0 pod0_s0_d0 pod0_s0_p0\n"));
        assert!(c.contains("http_access allow pod0 authed pod0_s1 pod0_s1_d0 pod0_s1_p0\n"));
        assert!(
            !c.contains("pod0_s1 pod0_s0"),
            "no session uses another's rules"
        );
        // Local services: exact, before the refusals of plain HTTP and private addresses.
        assert!(c.contains("acl pod0_s0_l0 dst 192.168.1.50\nacl pod0_s0_lp0 port 1234\n"));
        assert!(c.contains("acl pod0_s0_l1 dstdomain -n host.containers.internal\n"));
        assert!(
            position("http_access allow pod0 authed pod0_s0 pod0_s0_l0 pod0_s0_lp0")
                < position("http_access deny !CONNECT")
        );
        assert!(
            position("http_access deny pod0 !pod0_hosts") < position("http_access deny private")
        );
        assert!(c.contains(
            "acl pod0_hosts dstdomain -n api.anthropic.com chatgpt.com registry.npmjs.org\n"
        ));
        assert!(c.contains(
            "auth_param basic program /usr/lib/squid/basic_ncsa_auth /etc/squid/agent-run/passwd\n"
        ));
    }

