//! The dependency mirror: Reposilite with one repository per
//! remote in the policy's `mirror.remotes`, storing what it fetches. Builds reach Maven
//! repositories, Gradle distributions and the Android SDK only through it. It downloads
//! through the egress proxy from its own network, with its own allowlist; no tokens exist
//! and the web interface is off, so clients can only read.

use podman::{Namespace, Object, OnChange, Podman, PodmanError, Service};
use std::collections::BTreeMap;
use std::path::Path;

/// The name pods reach the mirror by.
pub const ALIAS: &str = "mirror";
pub const PORT: u16 = 8080;
pub const URL: &str = "http://mirror:8080";

/// Hosts a remote redirects to, which the mirror needs as well.
fn redirects(host: &str) -> &'static [&'static str] {
    match host {
        "plugins.gradle.org" => &["plugins-artifacts.gradle.org"],
        "services.gradle.org" => &[
            "downloads.gradle.org",
            "github.com",
            "objects.githubusercontent.com",
            "release-assets.githubusercontent.com",
        ],
        _ => &[],
    }
}

fn host(url: &str) -> &str {
    let rest = url.strip_prefix("https://").unwrap_or(url);
    rest.split('/').next().unwrap_or(rest)
}

/// The hosts the mirror may reach: each remote's, and where they redirect.
pub fn hosts(remotes: &BTreeMap<String, String>) -> Vec<String> {
    let mut hosts: Vec<String> = Vec::new();
    for url in remotes.values() {
        let host = host(url);
        for h in std::iter::once(host).chain(redirects(host).iter().copied()) {
            if !hosts.iter().any(|known| known == h) {
                hosts.push(h.to_owned());
            }
        }
    }
    hosts.sort();
    hosts
}

/// What Reposilite may store from a remote: distributions and the SDK need few types.
fn extensions(url: &str) -> &'static [&'static str] {
    if url.starts_with("https://services.gradle.org/") {
        &[".zip", ".sha256"]
    } else if url.starts_with("https://dl.google.com/android/repository") {
        &[".xml", ".zip"]
    } else {
        &[
            ".jar", ".war", ".aar", ".pom", ".xml", ".module", ".md5", ".sha1", ".sha256",
            ".sha512", ".asc", ".klib", ".zip", ".tar.gz", ".tar.xz", ".txt", ".json",
        ]
    }
}

fn json(value: &str) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Reposilite's shared configuration: a stored, read-only proxy repository per remote,
/// downloading through `proxy` (`host:port`).
pub fn shared_config(remotes: &BTreeMap<String, String>, proxy: &str) -> String {
    let repositories: Vec<String> = remotes
        .iter()
        .map(|(id, url)| {
            let extensions: Vec<String> = extensions(url).iter().map(|e| json(e)).collect();
            let timeout = if extensions.len() > 2 { 60 } else { 300 };
            format!(
                r#"      {{
        "id": {id},
        "visibility": "PUBLIC",
        "redeployment": false,
        "storageProvider": {{ "type": "fs", "quota": "100%", "mount": "", "filePermissions": "600" }},
        "proxied": [
          {{
            "reference": {url},
            "store": true,
            "allowedExtensions": [{extensions}],
            "connectTimeout": 10,
            "readTimeout": {timeout},
            "httpProxy": {proxy}
          }}
        ]
      }}"#,
                id = json(id),
                url = json(url),
                extensions = extensions.join(", "),
                proxy = json(&format!("HTTP {proxy}")),
            )
        })
        .collect();
    format!(
        "{{\n  \"maven\": {{\n    \"repositories\": [\n{}\n    ]\n  }}\n}}\n",
        repositories.join(",\n")
    )
}

/// Reposilite's local configuration: no web interface; no tokens exist.
pub const LOCAL_CONFIG: &str = "# Generated by agent-run; changes are overwritten.
hostname: 0.0.0.0
port: 8080
database: sqlite reposilite.db
sslEnabled: false
enforceSsl: false
webThreadPool: 12
ioThreadPool: 4
databaseThreadPool: 1
compressionStrategy: none
idleTimeout: 30000
bypassExternalCache: true
cachedLogSize: 64
defaultFrontend: false
basePath: /
debugEnabled: false
";

/// The mirror as a shared service, on its own internal network: its way out is the proxy.
pub fn service<'a>(podman: &'a Podman, namespace: &Namespace, state_dir: &Path) -> Service<'a> {
    Service {
        podman,
        container: namespace.name("mirror"),
        network: namespace.name("mirror"),
        internal: true,
        alias: ALIAS,
        config_dir: state_dir.join("mirror"),
        label: namespace.label(),
    }
}

pub struct Mirror<'a> {
    pub service: Service<'a>,
    /// What it stored; kept, so dependencies download once.
    pub volume: String,
    pub image: &'a str,
}

impl Mirror<'_> {
    /// Writes the configuration and makes sure the mirror runs with it, downloading through
    /// the proxy at `proxy` (`ip:port` on the mirror's network). Not by name: the mirror is on
    /// the pods' networks too, where `proxy` is the pods' address, and the proxy would apply a
    /// pod's allowlist. Reposilite reads its configuration at start, so a change restarts it.
    pub fn ensure(
        &self,
        remotes: &BTreeMap<String, String>,
        proxy: &str,
    ) -> Result<(), PodmanError> {
        let changed = self.service.write_config(&[
            ("configuration.cdn", LOCAL_CONFIG.to_owned()),
            ("configuration.shared.json", shared_config(remotes, proxy)),
        ])?;
        if !self.service.podman.exists(Object::Volume, &self.volume)? {
            self.service.podman.run(&[
                "volume",
                "create",
                "--label",
                &self.service.label,
                &self.volume,
            ])?;
        }
        let options: Vec<String> = [
            "--user", "977:977", "--memory", "1g", "--pids-limit", "256",
            "-v", &format!("{}:/app/config:ro,z", self.service.config_dir.display()),
            "-v", &format!("{}:/app/data:U,z", self.volume),
            "--tmpfs", "/var/log/reposilite:mode=0777", "--tmpfs", "/tmp:mode=1777",
            "-e", "REPOSILITE_OPTS=--local-configuration=/app/config/configuration.cdn --shared-configuration=/app/config/configuration.shared.json",
        ]
        .map(String::from)
        .into();
        self.service
            .ensure(&options, self.image, &[], changed, OnChange::Restart)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn remotes() -> BTreeMap<String, String> {
        [
            ("central", "https://repo.maven.apache.org/maven2"),
            ("gradle-plugins", "https://plugins.gradle.org/m2"),
            (
                "gradle-distributions",
                "https://services.gradle.org/distributions",
            ),
            ("android-sdk", "https://dl.google.com/android/repository"),
            ("google", "https://dl.google.com/dl/android/maven2"),
        ]
        .into_iter()
        .map(|(k, v)| (k.to_owned(), v.to_owned()))
        .collect()
    }

    #[test]
    fn the_mirror_reaches_its_remotes_and_their_redirects_only() {
        assert_eq!(
            hosts(&remotes()),
            [
                "dl.google.com",
                "downloads.gradle.org",
                "github.com",
                "objects.githubusercontent.com",
                "plugins-artifacts.gradle.org",
                "plugins.gradle.org",
                "release-assets.githubusercontent.com",
                "repo.maven.apache.org",
                "services.gradle.org",
            ]
        );
    }

    #[test]
    fn one_stored_repository_per_remote() {
        let config = shared_config(&remotes(), "proxy:3128");
        assert_eq!(config.matches("\"id\": ").count(), 5);
        assert!(config.contains("\"id\": \"android-sdk\""));
        assert!(config.contains("\"reference\": \"https://services.gradle.org/distributions\""));
        assert!(config.contains("\"allowedExtensions\": [\".zip\", \".sha256\"]"));
        assert!(config.contains("\"httpProxy\": \"HTTP proxy:3128\""));
        assert!(!config.contains(",\n    ]"), "no trailing comma");
        assert_eq!(json("a\"b\\c"), "\"a\\\"b\\\\c\"");
    }
}
